func content(s string) func() ([]byte, error) {
	return func() ([]byte, error) { return []byte(s), nil }
}

func errContent() func() ([]byte, error) {
	return func() ([]byte, error) { return nil, errors.New("not found") }
}

func TestClassifyReviewConfig(t *testing.T) {
	in := Input{File: gh.File{Path: ".github/agentic-review/config.yaml"}}
	if cls, _ := Classify(in); cls != ClassReviewConfig {
		t.Errorf("class = %s, want review-config", cls)
	}
	in2 := Input{File: gh.File{Path: ".github/workflows/review.yml"}, WorkflowPath: ".github/workflows/review.yml"}
	if cls, _ := Classify(in2); cls != ClassReviewConfig {
		t.Errorf("class = %s, want review-config for the invoking workflow file", cls)
	}
}

