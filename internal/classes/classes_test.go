func TestClassifyOrderReviewConfigBeatsCIConfig(t *testing.T) {
	// A path under .github/agentic-review/ that is ALSO the invoking
	// workflow path would be ambiguous only if it matched workflows/**;
	// here we assert review-config wins over the generic ci-config match
	// when both .github/agentic-review and .github/workflows could apply
	// to a config-guard-adjacent path.
	in := Input{File: gh.File{Path: ".github/agentic-review/config.yaml"}, WorkflowPath: ".github/workflows/review.yml"}
	if cls, _ := Classify(in); cls != ClassReviewConfig {
		t.Errorf("class = %s, want review-config to take priority", cls)
	}
}
