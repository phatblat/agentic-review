func TestClassifyGitattributesFalseSuppressesHeuristic(t *testing.T) {
	attrs := gitattributes.Parse([]byte("special.go -linguist-generated\n"))
	in := Input{
		File:        gh.File{Path: "special.go"},
		Attributes:  attrs,
		HeadContent: content("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage main\n"),
	}
	if cls, _ := Classify(in); cls != ClassSource {
		t.Errorf("class = %s, want source: explicit gitattributes false must suppress the marker heuristic", cls)
	}
}

